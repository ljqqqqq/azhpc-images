#!/bin/bash
set -euox pipefail

# =============================================================================
# Prerequisites: LTS kernel, package updates, GB200 config
# =============================================================================
# This script runs BEFORE the azhpc-images install.sh
# It handles:
#   - Kernel setup (LTS or GB200 nvidia kernel)
#   - Base package updates
#   - NVLink rackscale configurations (GRUB args, nouveau blacklist)
#   - GB200-specific configurations (PARTUUID)
#
# Environment variables:
#   OS_FAMILY        - OS family (ubuntu, alma, azurelinux)
#   DISTRO_VERSION   - Distro version (22.04, 24.04, etc.)
#   GPU_SKU          - GPU SKU (a100, h100, gb200, mi300x) - required
#   GB200_PARTUUID   - Disk PARTUUID for GB200 builds (None for non-GB200)
#   TARGET_NODE_TYPE - Target node type (azure_vm_regular/azure_vm_akshost/baremetal_1p/baremetal_3p)
# =============================================================================

####
# @Brief        : Configure apt/dpkg to wait for package-manager locks
# @Param        : None
# @RetVal       : 0 on success
####
configure_apt_lock_timeout() {
    if [[ "${OS_FAMILY}" != "ubuntu" ]]; then
        return 0
    fi

    echo "##[section]Configuring apt lock timeout"
    printf 'DPkg::Lock::Timeout "-1";\n' > /etc/apt/apt.conf.d/99dpkg-lock-timeout
}

####
# @Brief        : Turn off APT's automatic updates for the build and the shipped image
# @Param        : None
# @RetVal       : 0 on success
####
disable_automatic_apt_updates() {
    if [[ "${OS_FAMILY}" != "ubuntu" ]]; then
        return 0
    fi

    echo "##[section]Disabling automatic APT updates"

    # Stop background `apt-get update` and unattended-upgrade.
    # Disabling upgrades is important for package version control,
    # and disabling updates prevents unnecessary waits for the dpkg lock during builds.
    # Manually invoked apt is unaffected.
    cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "0";
APT::Periodic::Unattended-Upgrade "0";
EOF

    systemctl stop unattended-upgrades.service 2>/dev/null || true
    systemctl disable unattended-upgrades.service 2>/dev/null || true
}

####
# @Brief        : Wait for cloud-init before starting package operations
# @Param        : None
# @RetVal       : 0 on success
####
wait_for_cloud_init() {
    echo "Waiting for cloud-init to complete..."
    cloud-init status --wait || true
}

####
# @Brief        : Configure GB200-specific disk PARTUUID
# @Param        : partuuid - The PARTUUID to set
# @RetVal       : 0 on success
####
configure_gb200_partuuid() {
    local partuuid="${1:-None}"
    local target_variant="${TARGET_NODE_TYPE:-azure_vm_regular}"

    # Skip PARTUUID configuration for VR200, which is inconsistent with legacy image build now but both are placeholder
    if [[ "${partuuid}" == "None" || -z "${partuuid}" ]]; then
        echo "##[section]Skipping PARTUUID configuration (PARTUUID not specified)"
        return 0
    fi
    
    if [[ "${target_variant}" != "azure_vm_regular" ]]; then
        echo "##[section]Skipping PARTUUID configuration for ${target_variant}"
        return 0
    fi
    
    echo "##[section]Configuring GB200 disk PARTUUID: ${partuuid}"
    
    # Get boot device info
    local boot_device
    boot_device=$(findmnt -no SOURCE /boot/efi)
    local disk
    disk="/dev/$(lsblk -no PKNAME "${boot_device}")"
    local partition
    partition=$(lsblk -nrno PARTN "${boot_device}")
    
    echo "Boot device: ${boot_device}"
    echo "Disk: ${disk}, Partition: ${partition}"
    
    # Set PARTUUID using sgdisk
    sgdisk --partition-guid="${partition}:${partuuid}" "${disk}"
    
    # Update EFI boot entry
    local old_boot_entries
    old_boot_entries=$(efibootmgr -v | awk 'tolower($0) ~ /^boot[0-9a-f]{4}\*?[[:space:]]+ubuntu[[:space:]]/ && tolower($0) ~ /file\(\\efi\\ubuntu\\shimaa64\.efi\)/ {print substr($1, 5, 4)}')
    for boot_entry in ${old_boot_entries}; do
        efibootmgr -b "${boot_entry}" -B || true
    done
    efibootmgr -c -d "${disk}" -p "${partition}" -L "Ubuntu" -l '\EFI\ubuntu\shimaa64.efi'
    
    echo "GB200 PARTUUID configuration complete"
}

####
# @Brief        : Configure NVLink rackscale kernel boot settings
# @RetVal       : 0 on success
####
configure_nvlink_rackscale_kernel() {
    if [[ "${TARGET_NODE_TYPE:-azure_vm_regular}" != baremetal_* ]]; then
        sed -i '/^GRUB_CMDLINE_LINUX=/ s/"$/ iommu.passthrough=1 irqchip.gicv3_nolpi=y arm_smmu_v3.disable_msipolling=1 init_on_alloc=0 net.ifnames=0"/' /etc/default/grub.d/50-cloudimg-settings.cfg
    else
        echo "FW dma fix"
        sudo sed -i 's/GRUB_CMDLINE_LINUX=""/GRUB_CMDLINE_LINUX="efi=disable_early_pci_dma"/g' /etc/default/grub
        if [[ "${TARGET_NODE_TYPE:-azure_vm_regular}" == baremetal_1p && "${KERNEL_VERSION}" == "6.17" ]]; then
            cat > /etc/default/grub.d/config-acs.cfg <<'EOF'
# Generated by /usr/sbin/rdma_topo do not change. ACS settings for RDMA GPU Direct
GRUB_CMDLINE_LINUX="$GRUB_CMDLINE_LINUX pci=config_acs=\"xx111x0@0008:00:00.0;xx110x1@0008:02:00.0;xx101x1@0008:02:03.0;xx111x0@0009:00:00.0;xx110x1@0009:02:00.0;xx101x1@0009:02:01.0;xx111x0@0018:00:00.0;xx110x1@0018:02:00.0;xx101x1@0018:02:03.0;xx111x0@0019:00:00.0;xx110x1@0019:02:00.0;xx101x1@0019:02:01.0\""
EOF
            chmod 644 /etc/default/grub.d/config-acs.cfg
        fi
    fi

    echo 'blacklist nouveau' >> /etc/modprobe.d/blacklist.conf
    update-grub
}

####
# @Brief        : Install NVIDIA Grace-aware kernel for Ubuntu 24.04
# @RetVal       : 0 on success
####
install_ubuntu_nvidia_kernel() {
    echo "##[section]Installing NVIDIA Grace-aware kernel for Ubuntu 24.04"
    
    export NEEDRESTART_MODE=a
    
    # In-place refresh: ensure DKMS builds OFED modules in dependency order
    # (iser/isert/srp need mlnx-ofed-kernel built first, but DKMS autoinstall
    # processes modules alphabetically and would otherwise fail).
    if [[ -d /var/lib/dkms/mlnx-ofed-kernel ]]; then
        configure_ofed_dkms_build_depends
    fi
    local kernel_ver="${KERNEL_VERSION:-6.8}"
    install_ubuntu_kernel_packages noble "linux-azure-nvidia-${kernel_ver}"

    # Purge non-nvidia kernels
    apt-get purge -y linux-azure linux-image-azure

    # Remove non-nvidia kernel packages
    local packages_to_remove
    packages_to_remove=$(dpkg -l | awk '/linux-(azure|image|cloud-tools|headers|modules|tools)-6\.(14|17)/ && $2 !~ /nvidia/ {print $2}' || true)
    if [[ -n "${packages_to_remove}" ]]; then
        apt-get purge -y ${packages_to_remove}
    fi
    
    apt autoremove -y
    apt-get upgrade -y
    
    # Keep only the latest installed linux-azure-nvidia kernel
    local target_kernel
    target_kernel=$(dpkg -l | awk '/linux-image-[0-9].*-azure-nvidia/ {print $2}' | sed 's/linux-image-//g' | sort -V | tail -n1)
    
    for prefix in vmlinuz initrd.img config System.map; do
        for f in /boot/${prefix}-*-azure*; do
            [[ $f == *${target_kernel}* ]] || rm -f "$f"
        done
    done

    configure_nvlink_rackscale_kernel
    
    echo "NVIDIA kernel installation complete"
}

####
# @Brief        : Add OFED DKMS dependency overrides under /etc/dkms
# @Param        : None
# @RetVal       : 0 on success
####
configure_ofed_dkms_build_depends() {
    [[ -d /var/lib/dkms/mlnx-ofed-kernel ]] || return 0
    mkdir -p /etc/dkms

    cat > /etc/dkms/iser.conf <<'EOF'
BUILD_DEPENDS="mlnx-ofed-kernel"
EOF
    cat > /etc/dkms/isert.conf <<'EOF'
BUILD_DEPENDS="mlnx-ofed-kernel"
EOF
    cat > /etc/dkms/srp.conf <<'EOF'
BUILD_DEPENDS="mlnx-ofed-kernel"
EOF
}

####
# @Brief        : Ensure Ubuntu proposed suite exists and keep it at low priority
# @Desc         : Keeps proposed available but pinned low; explicit installs use -t <codename>-proposed
# @Param        : codename - Ubuntu codename (noble, jammy, ...)
# @RetVal       : 0 on success
####
configure_ubuntu_proposed_suite() {
    local codename=$1
    local pref_file=/etc/apt/preferences.d/99-ubuntu-proposed-low-priority.pref
    local has_proposed=false
    
    # Find any Deb822 .sources file that contains this codename
    local deb822_file
    deb822_file="/etc/apt/sources.list.d/ubuntu.sources"
    
    if [[ -f "${deb822_file}" ]]; then
        if grep -q "^Suites:.*${codename}-proposed" "${deb822_file}"; then
            has_proposed=true
        fi
        if [[ "${has_proposed}" != "true" ]]; then
            echo "##[section]Adding ${codename}-proposed in Deb822 format (${deb822_file})"
            sudo sed -i "/^Suites:.*${codename}[^-]/ s/$/ ${codename}-proposed/" "${deb822_file}"
            # Avoid duplicates
            sudo sed -i "s/ ${codename}-proposed ${codename}-proposed/ ${codename}-proposed/g" "${deb822_file}"
        fi
    else
        if [[ -f "/etc/apt/sources.list.d/${codename}-proposed.list" ]]; then
            has_proposed=true
        fi

        if [[ "${has_proposed}" != "true" ]]; then
            echo "##[section]Adding ${codename}-proposed in old list format"
            local mirror
            mirror=$(grep "^deb http" /etc/apt/sources.list 2>/dev/null | grep " ${codename} " | head -1 | awk '{print $2}')
            if [[ -z "${mirror}" ]]; then
                echo "##[warning]Could not detect mirror for ${codename}, skipping proposed suite"
                return 0
            fi
            sudo tee /etc/apt/sources.list.d/${codename}-proposed.list > /dev/null <<EOF
deb ${mirror} ${codename}-proposed main restricted universe multiverse
EOF
        fi
    fi
    
    echo "##[section]Ensuring ${codename}-proposed is low priority (pin file: ${pref_file})"
    # Keep proposed enabled but low priority unless explicitly targeted via -t
    sudo tee "${pref_file}" > /dev/null <<EOF
Package: *
Pin: release a=${codename}-proposed
Pin-Priority: 100
EOF
    sudo chmod 644 "${pref_file}"
}

####
# @Brief        : Keep Launchpad PPA at low priority
# @Desc         : Prevents accidental package upgrades from PPA unless explicitly requested
# @RetVal       : 0 on success
####
configure_ppa_low_priority() {
    local ppa_repo_name=$1
    local ppa_ref="${ppa_repo_name#ppa:}"
    local ppa_origin="LP-PPA-${ppa_ref//\//-}"

    local pref_file=/etc/apt/preferences.d/99-ubuntu-ppa-low-priority.pref

    echo "##[section]Configuring default low priority for Launchpad PPA packages: ${pref_file}"
    sudo tee "${pref_file}" > /dev/null <<EOF
Package: *
Pin: release o=${ppa_origin}
Pin-Priority: 100
EOF
    sudo chmod 644 "${pref_file}"
    sudo apt-get -y update
}

####
# @Brief        : Install Ubuntu kernel packages using one shared source policy
# @Desc         : PPA (exact meta-package version) takes precedence over proposed,
#                 then the default archive. Configure the source before probing extras.
# @Param        : codename       - Ubuntu codename (jammy, noble, resolute, ...)
# @Param        : kernel_package - Required kernel meta-package
# @Param        : ...            - Optional packages to install if available
# @RetVal       : 0 on success
####
install_ubuntu_kernel_packages() {
    local codename=$1
    local kernel_package=$2
    shift 2
    local use_ppa="${USE_UBUNTU_PPA_REPO:-false}"
    local use_proposed="${USE_UBUNTU_PROPOSED_SUITE:-false}"
    local apt_options=(-y)
    local packages=("${kernel_package}")
    local package

    if [[ "${use_ppa,,}" == "true" ]]; then
        if [[ "${UBUNTU_PPA_REPO_NAME:-}" != ppa:*/* ||
              -z "${UBUNTU_PPA_KERNEL_PATCH_VERSION:-}" ||
              "${UBUNTU_PPA_KERNEL_PATCH_VERSION}" == "None" ]]; then
            echo "ERROR: PPA kernel installation requires a PPA name and exact meta-package version" >&2
            return 1
        fi
        sudo add-apt-repository --no-update -y "${UBUNTU_PPA_REPO_NAME}"
        packages=("${kernel_package}=${UBUNTU_PPA_KERNEL_PATCH_VERSION}")
    elif [[ "${use_proposed,,}" == "true" ]]; then
        configure_ubuntu_proposed_suite "${codename}"
        apt_options+=(-t "${codename}-proposed")
    fi

    apt-get update
    for package in "$@"; do
        if apt-cache show "${package}" &>/dev/null; then
            packages+=("${package}")
        else
            echo "##[section]Optional kernel package ${package} is unavailable; skipping"
        fi
    done

    echo "##[section]Installing kernel packages: ${packages[*]}"
    apt-get install "${apt_options[@]}" "${packages[@]}"

    if [[ "${use_ppa,,}" == "true" ]]; then
        configure_ppa_low_priority "${UBUNTU_PPA_REPO_NAME}"
    fi
}

####
# @Brief        : Remove installed 4K Azure kernels after switching to 64K
# @Param        : kernel_ver - Target kernel minor version
# @RetVal       : 0 on success
####
purge_ubuntu_4k_kernel() {
    local kernel_ver=$1
    local packages_to_remove
    local packages=()

    # Match only 4K meta-packages and ABI packages ending in -azure. In particular,
    # keep shared packages such as linux-azure-7.0-headers-7.0.0-3019 and all 64K packages.
    packages_to_remove=$(dpkg -l | awk -v kernel_ver="${kernel_ver}" '
        $1 != "ii" { next }

        $2 ~ /^linux-(azure|image-azure|headers-azure|tools-azure|cloud-tools-azure|modules-extra-azure)$/ {
            print $2
            next
        }

        $2 ~ /^linux-(image(-unsigned)?|cloud-tools|headers|modules(-extra)?|tools)-/ &&
        index($2, "-" kernel_ver ".") && $2 ~ /-azure$/ { print $2 }
    ')

    if [[ -n "${packages_to_remove}" ]]; then
        if grep -Eq '64k|^linux-azure-[0-9]' <<< "${packages_to_remove}"; then
            echo "ERROR: purge list contains protected 64K/shared packages" >&2
            return 1
        fi
        mapfile -t packages <<< "${packages_to_remove}"
        printf 'Purging 4K kernel package: %s\n' "${packages[@]}"
        apt-get purge -y "${packages[@]}"
    fi
}

####
# @Brief        : Install LTS kernel for Ubuntu
# @Param        : OS version (e.g., 24.04, 22.04)
# @RetVal       : 0 on success
####
install_ubuntu_lts_kernel() {
    local version=$1
    
    # SKUs with rackscale NVLink use a special nvidia kernel, not LTS
    if [[ "${NVLINK_RACKSCALE}" == "true" && "${KERNEL_VERSION}" != "7.0" ]]; then
        install_ubuntu_nvidia_kernel
        return $?
    fi
    
    echo "##[section]Installing LTS kernel for Ubuntu ${version}"
    
    # Configure needrestart to prevent interactive prompts
    sed -i "s/#\$nrconf{restart} = 'i';/\$nrconf{restart} = 'a';/g" /etc/needrestart/needrestart.conf || true
    sed -i "s/#\$nrconf{kernelhints} = -1;/\$nrconf{kernelhints} = -1;/g" /etc/needrestart/needrestart.conf || true
    
    export NEEDRESTART_MODE=a

    case "${version}" in
        24.04)
            local kernel_ver="${KERNEL_VERSION:-6.8}"
            echo "##[section]Installing kernel ${kernel_ver} for Ubuntu 24.04"

            # Build list of kernel minor versions to purge (everything except the target)
            local all_kernel_minors="6.8 6.11 6.14 6.17 7.0"
            local purge_patterns=""
            for minor in $all_kernel_minors; do
                if [[ "$minor" != "$kernel_ver" ]]; then
                    purge_patterns+=" \"linux-image-${minor}*\" \"linux-azure-${minor}*\" \"linux-cloud-tools-${minor}*\" \"linux-headers-${minor}*\" \"linux-modules-${minor}*\" \"linux-tools-${minor}*\""
                fi
            done
            if [[ -d /var/lib/dkms/mlnx-ofed-kernel ]]; then
                configure_ofed_dkms_build_depends
            fi

            local kernel_package="linux-azure-${kernel_ver}"
            local extra_packages=("linux-modules-extra-azure-${kernel_ver}")
            local use_ppa="${USE_UBUNTU_PPA_REPO:-false}"
            # The 7.0 NVLink rackscale PPA publishes the 64K flavor under this
            # unversioned meta-package. It must not pull in the 4K modules-extra.
            if [[ "${NVLINK_RACKSCALE}" == "true" && "${kernel_ver}" == "7.0" && "${use_ppa,,}" == "true" ]]; then
                kernel_package="linux-azure-64k"
                extra_packages=()
            fi
            install_ubuntu_kernel_packages noble "${kernel_package}" "${extra_packages[@]}"
            
            # Purge non-target kernels
            eval apt-get purge -y linux-azure linux-image-azure $purge_patterns || true
            # Also purge the LTS meta-package if we're not using it
            if [[ "$kernel_ver" != "6.8" ]]; then
                apt-get purge -y linux-azure-lts-24.04 || true
            fi

            if [[ "${kernel_package}" == "linux-azure-64k" ]]; then
                purge_ubuntu_4k_kernel "${kernel_ver}"
            fi

            if [[ "${NVLINK_RACKSCALE}" == "true" && "${KERNEL_VERSION}" == "7.0" ]]; then
                configure_nvlink_rackscale_kernel
            fi

            apt autoremove -y
            apt upgrade -y

            ;;
            
        26.04)
            # Ubuntu 26.04 (Resolute Raccoon) ships linux-azure-7.0 (kernel 7.0.0-*-azure)
            # as the versioned Azure meta-package. Allow KERNEL_VERSION to override.
            local kernel_ver="${KERNEL_VERSION:-7.0}"
            echo "##[section]Installing kernel ${kernel_ver} for Ubuntu 26.04"

            # linux-modules-extra-azure-${kernel_ver} is not published for 7.0 in resolute;
            # contents were folded into linux-modules-azure-${kernel_ver}. Install only if present.
            install_ubuntu_kernel_packages resolute "linux-azure-${kernel_ver}" "linux-modules-extra-azure-${kernel_ver}"

            apt autoremove -y
            apt upgrade -y

            update-grub
            ;;

        22.04)
            install_ubuntu_kernel_packages jammy linux-azure-lts-22.04
            # Purge non-LTS kernels
            apt-get purge -y \
                linux-azure linux-image-azure \
                "linux-image-6.*" "linux-azure-6.*" \
                "linux-cloud-tools-6.*" "linux-headers-6.*" \
                "linux-modules-6.*" "linux-tools-6.*"
            
            apt upgrade -y

            ;;
            
        *)
            echo "##[warning]No LTS kernel configuration for Ubuntu ${version}"
            apt update && apt upgrade -y
            ;;
    esac
    
    echo "Ubuntu LTS kernel installation complete"
}

configure_rhel_lvm() {
    local volume target_bytes current_bytes filesystem
    local root_pv disk partition grow_output
    local volumes=(homelv tmplv rootlv varlv usrlv)

    for volume in "${volumes[@]}"; do
        filesystem=$(findmnt -n -o FSTYPE --source "/dev/rootvg/${volume}")
        if [[ "${filesystem}" != "xfs" ]]; then
            echo "ERROR: expected a mounted XFS filesystem on /dev/rootvg/${volume}" >&2
            return 1
        fi
    done

    root_pv=$(pvs --noheadings -o pv_name --select vg_name=rootvg | xargs)
    if [[ ! -b "${root_pv}" ]]; then
        echo "ERROR: expected a single physical volume for rootvg" >&2
        return 1
    fi
    root_pv=$(readlink -f "${root_pv}")
    disk=$(lsblk -ndo PKNAME "${root_pv}")
    partition=$(cat "/sys/class/block/${root_pv##*/}/partition")
    if [[ -z "${disk}" || ! "${partition}" =~ ^[0-9]+$ ]]; then
        echo "ERROR: unable to determine the rootvg disk partition" >&2
        return 1
    fi
    if grow_output=$(growpart "/dev/${disk}" "${partition}" 2>&1); then
        echo "${grow_output}"
    elif [[ "${grow_output}" == NOCHANGE:* ]]; then
        echo "${grow_output}"
    else
        echo "ERROR: unable to grow the rootvg partition: ${grow_output}" >&2
        return 1
    fi
    pvresize "${root_pv}"

    for volume in homelv:10 tmplv:12 rootlv:24 varlv:48 usrlv:24; do
        target_bytes=$(( ${volume#*:} * 1024 * 1024 * 1024 ))
        volume=${volume%:*}
        current_bytes=$(lvs --noheadings --units b --nosuffix -o lv_size "/dev/rootvg/${volume}")
        if awk -v current="${current_bytes}" -v target="${target_bytes}" 'BEGIN { exit !(current < target) }'; then
            lvextend -L "${target_bytes}B" "/dev/rootvg/${volume}"
        fi
    done

    for volume in "${volumes[@]}"; do
        xfs_growfs "/dev/rootvg/${volume}"
    done
    df -h
}

####
# @Brief        : Update packages for RHEL-based distros (Alma, Azure Linux)
# @Param        : OS type (alma, azurelinux)
# @RetVal       : 0 on success
####
update_rhel_packages() {
    local os_family=$1

    if ! command -v dnf &> /dev/null; then
        echo "##[warning]dnf package manager not found. Cannot update packages for ${os_family}."
        return 0
    fi
    
    echo "##[section]Updating packages for ${os_family}"

    if [[ "${os_family}" == "rhel" ]]; then
        cloud-init status --wait
        if [[ "${REFRESH_MODE:-false}" != "true" ]]; then
            configure_rhel_lvm
        fi
        dnf --disablerepo='*' --enablerepo='rhui-microsoft-*' update -y 'rhui*'
    fi
    
    dnf update -y --refresh
    dnf install -y git
    
    if [[ "${os_family}" == "azurelinux"* ]]; then
        echo "Configuring Azure Linux specific settings..."
        sed -i 's/lockdown=integrity /lockdown=integrity ipv6.disable=1/' /etc/default/grub
        grub2-mkconfig -o /boot/grub2/grub.cfg
        sed -i '/umask 007/d' /etc/profile
    fi
    
    echo "Package update complete"
}

####
# @Brief        : Enable DNF versionlock for later install scripts
# @Param        : None
# @RetVal       : 0 on success
####
configure_dnf_versionlock() {
    if ! command -v dnf &> /dev/null; then
        return 0
    fi

    echo "##[section]Configuring dnf versionlock"

    if ! dnf install -y 'dnf-command(versionlock)' && ! dnf install -y dnf-plugins-core; then
        echo "ERROR: failed to install the DNF versionlock plugin" >&2
        return 1
    fi

    local plugin_dir=/etc/dnf/plugins
    local locklist=${plugin_dir}/versionlock.list
    local config=${plugin_dir}/versionlock.conf

    mkdir -p "${plugin_dir}"
    touch "${locklist}"
    cat > "${config}" <<EOF
[main]
enabled = 1
locklist = ${locklist}
EOF

    if ! dnf versionlock list >/dev/null; then
        echo "ERROR: the DNF versionlock plugin is not functional" >&2
        return 1
    fi
}

# =============================================================================
# Main execution
# =============================================================================

echo "========================================="
echo "Prerequisites: Kernel, Package Updates"
echo "OS: ${OS_FAMILY:-unknown} ${DISTRO_VERSION:-unknown}"
echo "GPU SKU: ${GPU_SKU:?GPU_SKU is required}"
echo "Target Image Variant: ${TARGET_NODE_TYPE:-azure_vm_regular}"
echo "=========================================="

configure_apt_lock_timeout
disable_automatic_apt_updates
 
if [[ "${GPU_SKU}" == "GB200" && "${DISTRO_VERSION}" == "24.04" ]]; then
    # Configure GB200 PARTUUID if specified
    configure_gb200_partuuid "${GB200_PARTUUID:-None}"
fi

# Wait for cloud-init before any package operations. Subsequent apt commands
# wait for package-manager locks through DPkg::Lock::Timeout.
if [[ "${OS_FAMILY}" == "ubuntu" ]]; then
    wait_for_cloud_init
fi

# OS-specific prerequisites
case "${OS_FAMILY}" in
    ubuntu)
        install_ubuntu_lts_kernel "${DISTRO_VERSION}"
        ;;
    *)
        update_rhel_packages "${OS_FAMILY}"
        configure_dnf_versionlock
        ;;
esac

echo "=========================================="
echo "Prerequisites Complete"
echo "Kernel: $(uname -r)"
echo "=========================================="
